// Builds optimised, responsive media from /media-src into /public/media and
// writes a typed manifest to src/lib/media.generated.ts.
//
//   npm run media                 (images + video)
//   npm run media -- --images-only
//
// Images → /public/media/img/<name>/<width>.webp
// Video  → /public/media/video/<name>-{1080,720}.mp4 + <name>-poster.webp
import { readdir, mkdir, writeFile, stat, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, parse, dirname } from "node:path";
import { spawnSync } from "node:child_process";
import sharp from "sharp";

const ROOT = process.cwd();
const SRC_IMG = join(ROOT, "media-src/images");
const SRC_VID = join(ROOT, "media-src/video");
const OUT_IMG = join(ROOT, "public/media/img");
const OUT_VID = join(ROOT, "public/media/video");
const MANIFEST = join(ROOT, "src/lib/media.generated.ts");

const WIDTHS = [480, 960, 1440, 1920, 2560];
const imagesOnly = process.argv.includes("--images-only");

const toHex = ({ r, g, b }) => "#" + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");

async function buildImages() {
  const files = (await readdir(SRC_IMG)).filter((f) => /\.(webp|jpe?g|png)$/i.test(f)).sort();
  const manifest = {};

  for (const file of files) {
    const name = parse(file).name;
    const input = join(SRC_IMG, file);
    const outDir = join(OUT_IMG, name);
    await mkdir(outDir, { recursive: true });

    const meta = await sharp(input, { failOn: "none" }).metadata();
    // EXIF orientation can swap width/height
    const rotated = meta.orientation && meta.orientation >= 5;
    const w0 = (rotated ? meta.height : meta.width) ?? 0;
    const h0 = (rotated ? meta.width : meta.height) ?? 0;
    const graphic = /^(banner-wide|collection-|lockup|strip-)/.test(name);

    const widths = WIDTHS.filter((w) => w < w0);
    widths.push(Math.min(w0, 2560));
    const unique = [...new Set(widths)].sort((a, b) => a - b);

    for (const w of unique) {
      const dest = join(outDir, `${w}.webp`);
      if (existsSync(dest)) continue;
      await sharp(input, { failOn: "none" })
        .rotate()
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: graphic ? 88 : 80, effort: 5, alphaQuality: 100 })
        .toFile(dest);
    }
    // sizes that are no longer produced
    for (const f of await readdir(outDir)) {
      const w = Number(parse(f).name);
      if (f.endsWith(".webp") && !unique.includes(w)) await rm(join(outDir, f));
    }

    const { dominant } = await sharp(input, { failOn: "none" }).stats();
    manifest[name] = { w: w0, h: h0, widths: unique, color: toHex(dominant), alpha: !!meta.hasAlpha };
    process.stdout.write(`  img  ${name.padEnd(28)} ${String(w0).padStart(4)}x${String(h0).padEnd(4)} [${unique.join(", ")}]\n`);
  }

  const body =
    "// AUTO-GENERATED by scripts/build-media.mjs — do not edit by hand.\n" +
    "export const mediaManifest = " +
    JSON.stringify(manifest, null, 2) +
    " as const;\n\nexport type MediaName = keyof typeof mediaManifest;\n";
  await mkdir(dirname(MANIFEST), { recursive: true });
  await writeFile(MANIFEST, body);
  console.log(`\n  manifest → ${MANIFEST} (${files.length} images)`);
}

function ffmpeg(args) {
  const r = spawnSync("ffmpeg", ["-v", "error", "-y", ...args], { stdio: "inherit" });
  if (r.status !== 0) throw new Error("ffmpeg failed: " + args.join(" "));
}

// name → poster frame time (s). Every hero clip is a silent loop.
const VIDEOS = {
  hero: { poster: 1.2 },
};

async function buildVideos() {
  await mkdir(OUT_VID, { recursive: true });
  for (const [name, cfg] of Object.entries(VIDEOS)) {
    const input = join(SRC_VID, `${name}.mp4`);
    if (!existsSync(input)) continue;
    const video = ["-an", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-preset", "medium", "-profile:v", "high", "-level", "4.1"];
    const out1080 = join(OUT_VID, `${name}-1080.mp4`);
    const out720 = join(OUT_VID, `${name}-720.mp4`);
    const poster = join(OUT_VID, `${name}-poster.webp`);
    if (!existsSync(out1080)) ffmpeg(["-i", input, ...video, "-crf", "25", "-vf", "scale=1920:-2", out1080]);
    if (!existsSync(out720)) ffmpeg(["-i", input, ...video, "-crf", "27", "-vf", "scale=1280:-2", out720]);
    if (!existsSync(poster)) ffmpeg(["-ss", String(cfg.poster), "-i", input, "-frames:v", "1", "-vf", "scale=1920:-2", "-c:v", "libwebp", "-quality", "82", poster]);
    for (const f of [out1080, out720, poster]) {
      const s = await stat(f);
      console.log(`  vid  ${parse(f).base.padEnd(28)} ${(s.size / 1024 / 1024).toFixed(2)} MB`);
    }
  }
}

console.log("Building media…");
await buildImages();
if (!imagesOnly) await buildVideos();
console.log("Done.");
