// Brand assets from the real artwork:
//   media-src/brand/logo.png          — the THE monogram (white on transparent)
//   media-src/brand/lockup-sheet.png  — the four-mark lockup + tagline (on white)
//
//   npm run brand
//
// Writes public/brand/*.png (ink / bone / amber tints), the favicon set, the
// social share image, and src/lib/brand.generated.ts — the monogram as a
// bitmap, which the Tower component lights up window by window.
import { mkdir, writeFile, unlink } from "node:fs/promises";
import { existsSync } from "node:fs";
import sharp from "sharp";

const BONE = { r: 243, g: 241, b: 236 };
const INK = { r: 13, g: 13, b: 13 };
const AMBER = { r: 240, g: 179, b: 67 };
const NIGHT = "#06080f";

await mkdir("public/brand", { recursive: true });

/** Build a flat-colour PNG from a single-channel alpha buffer. */
async function tinted(alpha, w, h, color, out, resize) {
  // join first, resize second — sharp would otherwise resize the base before joining the channel
  const joined = await sharp({ create: { width: w, height: h, channels: 3, background: color } })
    .joinChannel(alpha, { raw: { width: w, height: h, channels: 1 } })
    .png()
    .toBuffer();
  let img = sharp(joined);
  if (resize) img = img.resize(resize);
  await img.png({ compressionLevel: 9 }).toFile(out);
  const m = await sharp(out).metadata();
  console.log(`  ${out.padEnd(36)} ${m.width}x${m.height}`);
}

// ── 1. the monogram ───────────────────────────────────────────────
// Trim on the alpha channel alone: the transparent pixels carry mixed RGB.
const LOGO = "media-src/brand/logo.png";
// (two passes: sharp would otherwise trim the RGBA image before extracting the channel)
const full = await sharp(LOGO).extractChannel("alpha").raw().toBuffer({ resolveWithObject: true });
const rawIn = { raw: { width: full.info.width, height: full.info.height, channels: 1 } };
const t = await sharp(full.data, rawIn).trim({ threshold: 20 }).toBuffer({ resolveWithObject: true });
// trim reports the box but hands back the untrimmed stride, so crop it ourselves
const monoBox = { left: -t.info.trimOffsetLeft, top: -t.info.trimOffsetTop, width: t.info.width, height: t.info.height };
const monoAlpha = await sharp(full.data, rawIn).extract(monoBox).extractChannel(0).raw().toBuffer();
console.log(`  monogram alpha ${full.info.width}x${full.info.height} → box ${monoBox.left},${monoBox.top} ${monoBox.width}x${monoBox.height} (${monoAlpha.length} bytes)`);
for (const [tone, color] of [
  ["ink", INK],
  ["bone", BONE],
  ["amber", AMBER],
]) {
  await tinted(monoAlpha, monoBox.width, monoBox.height, color, `public/brand/mark-${tone}.png`, { width: 480 });
}

// ── 2. the lockup marks, lifted off their white sheet ─────────────
// sharp runs trim before extract whatever the call order, so crop in two passes.
const SHEET = "media-src/brand/lockup-sheet.png";
const marks = {
  "mark-kaleido": { left: 520, top: 230, width: 530, height: 430 },
  "mark-the": { left: 1190, top: 290, width: 540, height: 370 },
  "mark-scratch": { left: 1840, top: 240, width: 420, height: 420 },
  tagline: { left: 380, top: 700, width: 1580, height: 140 },
  lockup: { left: 20, top: 220, width: 2310, height: 640 },
};
for (const [name, box] of Object.entries(marks)) {
  const cropped = await sharp(SHEET).flatten({ background: "#ffffff" }).extract(box).png().toBuffer();
  const crop = await sharp(cropped).trim({ background: "#ffffff", threshold: 40 }).png().toBuffer();
  const m = await sharp(crop).metadata();
  // darkness becomes opacity
  const alpha = await sharp(crop).greyscale().negate().raw().toBuffer();
  for (const [tone, color] of [
    ["ink", INK],
    ["bone", BONE],
  ]) {
    await tinted(alpha, m.width, m.height, color, `public/brand/${name}-${tone}.png`, name === "lockup" ? { width: 1600 } : undefined);
  }
}

// ── 3. the monogram as a bitmap, for the Tower ────────────────────
const GRID = 25;
const small = await sharp(monoAlpha, { raw: { width: monoBox.width, height: monoBox.height, channels: 1 } })
  .resize(GRID, GRID, { fit: "fill", kernel: "lanczos3" })
  .raw()
  .toBuffer({ resolveWithObject: true });
const ch = small.info.channels; // raw single-channel input may come back as RGB
const rows = [];
for (let y = 0; y < GRID; y++) {
  let row = "";
  for (let x = 0; x < GRID; x++) row += small.data[(y * GRID + x) * ch] > 96 ? "1" : "0";
  rows.push(row);
}
await writeFile(
  "src/lib/brand.generated.ts",
  "// AUTO-GENERATED by scripts/build-brand.mjs — the THE monogram as a bitmap.\n" +
    `export const MONOGRAM_SIZE = ${GRID};\n` +
    "export const MONOGRAM: readonly string[] = [\n" +
    rows.map((r) => `  "${r}",`).join("\n") +
    "\n];\n",
);
console.log("  monogram bitmap:\n" + rows.map((r) => "    " + r.replace(/1/g, "█").replace(/0/g, "·")).join("\n"));

// ── 4. favicon set — the mark in bone on night ────────────────────
async function iconPng(size, out) {
  const mark = await sharp("public/brand/mark-bone.png")
    .resize({ width: Math.round(size * 0.72), height: Math.round(size * 0.72), fit: "inside" })
    .png()
    .toBuffer();
  const mm = await sharp(mark).metadata();
  await sharp({ create: { width: size, height: size, channels: 4, background: NIGHT } })
    .composite([{ input: mark, left: Math.round((size - mm.width) / 2), top: Math.round((size - mm.height) / 2) }])
    .png()
    .toFile(out);
}
await iconPng(64, "src/app/icon.png");
await iconPng(180, "src/app/apple-icon.png");

// favicon.ico with an embedded 48px PNG (valid in every browser)
await iconPng(48, "public/brand/_fav48.png");
const png48 = await sharp("public/brand/_fav48.png").png().toBuffer();
await unlink("public/brand/_fav48.png");
const header = Buffer.alloc(6);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(1, 4);
const entry = Buffer.alloc(16);
entry.writeUInt8(48, 0);
entry.writeUInt8(48, 1);
entry.writeUInt16LE(1, 4);
entry.writeUInt16LE(32, 6);
entry.writeUInt32LE(png48.length, 8);
entry.writeUInt32LE(22, 12);
if (existsSync("src/app/favicon.ico")) await unlink("src/app/favicon.ico");
await writeFile("src/app/favicon.ico", Buffer.concat([header, entry, png48]));

// ── 5. social share image: the lit mark over night, tagline beneath ──
const OG_W = 1200;
const OG_H = 630;
const ogMark = await sharp("public/brand/mark-amber.png").resize({ height: 330 }).png().toBuffer();
const ogTag = await sharp("public/brand/tagline-bone.png").resize({ width: 760 }).png().toBuffer();
const mk = await sharp(ogMark).metadata();
const tg = await sharp(ogTag).metadata();
await sharp({ create: { width: OG_W, height: OG_H, channels: 4, background: NIGHT } })
  .composite([
    { input: ogMark, left: Math.round((OG_W - mk.width) / 2), top: 96 },
    { input: ogTag, left: Math.round((OG_W - tg.width) / 2), top: OG_H - tg.height - 72 },
  ])
  .jpeg({ quality: 90 })
  .toFile("public/og.jpg");

console.log("brand assets written: public/brand/*, src/app/icon.png, apple-icon.png, favicon.ico, public/og.jpg, src/lib/brand.generated.ts");
